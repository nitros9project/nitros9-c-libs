/* Historical scalar aliases, sharing the fixed-width definitions. */
#ifndef _TYPES_H
#define _TYPES_H
#include <stdint.h>
#define _CHAR8_T
#define _INT8_T
#define _INT16_T
#define _INT32_T
typedef char char8_t;
typedef uint8_t u_char_t;
typedef uint8_t uchar8_t;
typedef uint8_t u_int8_t;
typedef uint16_t u_int16_t;
typedef uint32_t u_int32_t;
#endif
